"""Step 4 - bundle everything the web app needs into web/data/data.js

    python scripts/04_export.py
"""
import base64
import json
from datetime import date

import config as C


def main():
    zones = {}
    for z in C.ZONES:
        p = C.zone_paths(z)["json"]
        if p.exists():
            zones[z] = json.loads(p.read_text(encoding="utf-8"))
            dist = C.DATA / "work" / f"{z}_dist.json"                 # optional optical cross-check (05_dist.py)
            if dist.exists():
                zones[z]["dist"] = json.loads(dist.read_text(encoding="utf-8"))
        else:
            print(f"(no {z}.json yet - run 03_fire.py --zone {z})")
    facts = json.loads((C.DATA / "facts.json").read_text(encoding="utf-8"))
    inventory = json.loads((C.DATA / "inventory.json").read_text(encoding="utf-8"))
    payload = {
        "generated": date.today().isoformat(),
        "demo": any(z.get("demo") for z in zones.values()),
        "order": [z for z in ("avila", "gironde", "sefrou") if z in zones],
        "zones": zones, "facts": facts, "inventory": inventory,
    }
    C.WEB_DATA.mkdir(parents=True, exist_ok=True)
    # the per-pixel radar history (used by "Inspect a point") goes to one small binary file per fire,
    # fetched by the site only when needed: data.js stays light and the page opens fast
    for k, z in zones.items():
        cube = z.get("cube")
        if cube and "b64" in cube:
            name = f"cube_{k}.bin"
            (C.WEB_DATA / name).write_bytes(base64.b64decode(cube.pop("b64")))
            cube["src"] = f"data/{name}"
    out = C.WEB_DATA / "data.js"
    out.write_text("// generated by scripts/04_export.py\nwindow.NABD = " + json.dumps(payload) + ";\n", encoding="utf-8")
    print(f"wrote {out} ({out.stat().st_size / 1e3:.0f} kB)")
    for k, z in zones.items():
        b = z["burn"]
        print(f"  {k:8s} radar {b['area_ha']:>7,} ha | official {z['official_ha']:>7,} ha | {len(z['acquisitions'])} passes")


if __name__ == "__main__":
    main()
